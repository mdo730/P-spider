/** 按当前状态/行动挑一条短语 */
export function pickPhrase(s: PetState): string {
  const cats: PhraseCategory[] = ['idle'];
  if (isSick(s)) cats.push('sick');
  if (s.task?.type === 'work') cats.push('work');
  if (s.task?.type === 'study') cats.push('study');
  if (s.satiety < LOW_THRESHOLD) cats.push('hungry');
  if (s.cleanliness < LOW_THRESHOLD) cats.push('dirty');
  if (s.mood < MOOD_SAD) cats.push('sad');
  else if (s.mood >= MOOD_HAPPY && !isSick(s)) cats.push('happy');

  const cat = cats[Math.floor(Math.random() * cats.length)];
  const list = PHRASES[cat];
  return list[Math.floor(Math.random() * list.length)];
}
